// Turns the TFDA food nutrition CSV (20_2.csv, one row per food per
// analyte) into an idempotent seed migration.
//   npm run tfda:seed -w @gac/api -- <20_2.csv> <out.sql>
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export interface TfdaFood {
  ref: string;
  name: string;
  aliases: string | null;
  category: string | null;
  kcal: number;
  proteinG: number | null;
  carbG: number | null;
  fatG: number | null;
}

/** Minimal RFC 4180 parser: quoted fields, "" escapes, CRLF or LF. */
function parseRows(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    if (quoted) {
      if (ch !== '"') field += ch;
      else if (text[i + 1] === '"') {
        field += '"';
        i++;
      } else quoted = false;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const text = (v: string | undefined) => (v?.trim() ? v.trim() : null);
const num = (v: string | undefined) => {
  const t = text(v);
  if (t === null) return null;
  const n = Number(t);
  return Number.isFinite(n) ? n : null;
};

export function parseTfdaCsv(csv: string): TfdaFood[] {
  const [header, ...rows] = parseRows(csv.replace(/^\uFEFF/, ""));
  if (!header) return [];
  const col = (name: string) => {
    const i = header.indexOf(name);
    if (i < 0) throw new Error(`missing column: ${name}`);
    return i;
  };
  const [iRef, iName, iAliases, iCategory, iItem, iValue] = [
    "整合編號",
    "樣品名稱",
    "俗名",
    "食品分類",
    "分析項",
    "每100克含量",
  ].map(col) as [number, number, number, number, number, number];

  const byRef = new Map<string, TfdaFood>();
  for (const r of rows) {
    const ref = text(r[iRef]);
    if (!ref) continue;
    let food = byRef.get(ref);
    if (!food) {
      food = {
        ref,
        name: r[iName]!.trim(),
        aliases: text(r[iAliases]),
        category: text(r[iCategory]),
        kcal: NaN,
        proteinG: null,
        carbG: null,
        fatG: null,
      };
      byRef.set(ref, food);
    }
    switch (r[iItem]) {
      case "熱量":
        food.kcal = num(r[iValue]) ?? NaN;
        break;
      case "粗蛋白":
        food.proteinG = num(r[iValue]);
        break;
      case "總碳水化合物":
        food.carbG = num(r[iValue]);
        break;
      case "粗脂肪":
        food.fatG = num(r[iValue]);
        break;
    }
  }
  const foods = [...byRef.values()];
  const bad = foods.find((f) => Number.isNaN(f.kcal));
  if (bad) throw new Error(`food ${bad.ref} has no 熱量`);
  return foods;
}

const str = (v: string | null) =>
  v === null ? "null" : `'${v.replaceAll("'", "''")}'`;
const numSql = (v: number | null) => (v === null ? "null" : String(v));

export function seedSql(foods: TfdaFood[]): string {
  const values = [...foods]
    .sort((a, b) => (a.ref < b.ref ? -1 : a.ref > b.ref ? 1 : 0))
    .map(
      (f) =>
        `  ('tfda', ${str(f.ref)}, ${str(f.name)}, ${str(f.aliases)}, ${str(f.category)}, ${numSql(f.kcal)}, ${numSql(f.proteinG)}, ${numSql(f.carbG)}, ${numSql(f.fatG)})`,
    );
  return `-- TFDA food nutrition seed (generated by apps/api/scripts/tfda-seed.ts).
-- One row per food, values per 100 g. Idempotent via on conflict.
insert into "foods" ("source", "source_ref", "name", "aliases", "category", "kcal_per_100g", "protein_per_100g", "carb_per_100g", "fat_per_100g") values
${values.join(",\n")}
on conflict ("source", "source_ref") do update set
  "name" = excluded."name",
  "aliases" = excluded."aliases",
  "category" = excluded."category",
  "kcal_per_100g" = excluded."kcal_per_100g",
  "protein_per_100g" = excluded."protein_per_100g",
  "carb_per_100g" = excluded."carb_per_100g",
  "fat_per_100g" = excluded."fat_per_100g";
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) {
    console.error("usage: tfda-seed <20_2.csv> <out.sql>");
    process.exit(1);
  }
  const foods = parseTfdaCsv(readFileSync(input, "utf8"));
  writeFileSync(output, seedSql(foods));
  console.log(`wrote ${foods.length} foods to ${output}`);
}
